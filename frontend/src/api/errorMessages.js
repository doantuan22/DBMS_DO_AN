const VIETNAMESE = /[àáảãạăằắẳẵặâầấẩẫậèéẻẽẹêềếểễệìíỉĩịòóỏõọôồốổỗộơờớởỡợùúủũụưừứửữựỳýỷỹỵđ]/i;
// Codes whose server text mixes English with Vietnamese words; always use the table.
const ALWAYS_TABLE = new Set(['INVALID_PAYMENT_RESULT']);

/** Message shown to the user for an API error payload. */
export function localizeApiError({ code, message, status } = {}) {
  const text = typeof message === 'string' ? message : '';
  if (text && VIETNAMESE.test(text) && !ALWAYS_TABLE.has(code)) return text;
  return ERROR_MESSAGES[code] ?? STATUS_FALLBACK[status] ?? (text || `Lỗi ${status ?? ''}`.trim());
}
