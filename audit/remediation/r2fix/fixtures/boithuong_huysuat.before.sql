-- One immutable compensation entry per order; written atomically with cancellation and points.
CREATE TABLE dbo.BOITHUONG_HUYSUAT (
    DonDatVeID INT NOT NULL CONSTRAINT PK_BOITHUONG_HUYSUAT PRIMARY KEY,
    SuatChieuID INT NOT NULL,
    NguoiDungID INT NOT NULL,
    TongTienVe DECIMAL(18,2) NOT NULL,
    TongTienDoAn DECIMAL(18,2) NOT NULL,
    TienGiamGia DECIMAL(18,2) NOT NULL,
    TienVeThucTra DECIMAL(38,6) NOT NULL,
    DiemCong BIGINT NOT NULL,
    NgayBoiThuong DATETIME2 NOT NULL,
    NguoiThucHienID INT NULL,
    CONSTRAINT FK_BOITHUONG_HUYSUAT_Don FOREIGN KEY (DonDatVeID) REFERENCES dbo.DONDATVE(DonDatVeID),
    CONSTRAINT FK_BOITHUONG_HUYSUAT_Suat FOREIGN KEY (SuatChieuID) REFERENCES dbo.SUATCHIEU(SuatChieuID),
    CONSTRAINT FK_BOITHUONG_HUYSUAT_Khach FOREIGN KEY (NguoiDungID) REFERENCES dbo.NGUOIDUNG(NguoiDungID),
    CONSTRAINT FK_BOITHUONG_HUYSUAT_NguoiThucHien FOREIGN KEY (NguoiThucHienID) REFERENCES dbo.NGUOIDUNG(NguoiDungID),
    CONSTRAINT CK_BOITHUONG_HUYSUAT_Tien CHECK (TienVeThucTra >= 0),
    CONSTRAINT CK_BOITHUONG_HUYSUAT_Diem CHECK (DiemCong >= 0)
);
GO
